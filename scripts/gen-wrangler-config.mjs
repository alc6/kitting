#!/usr/bin/env node
// Generates wrangler.jsonc (gitignored) from wrangler.example.jsonc and environment
// variables. Used by the deploy workflow and for local `npm run config`.
//
// Required: KITTING_DOMAIN, D1_DATABASE_ID, TEAM_DOMAIN, ACCESS_AUD, ADMIN_EMAILS
// Optional: WORKER_NAME (kitting), D1_DATABASE_NAME (kitting), DEFAULT_LOCALE (en), CURRENCY (EUR)
//
// The generated config always runs in production mode: ENVIRONMENT=production and an
// empty DEV_AUTH_EMAIL, so the development auth bypass can never reach a deployment.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

/** Removes // and /* *\/ comments outside of strings. */
export function stripJsonComments(text) {
	let out = "";
	let inString = false;
	for (let i = 0; i < text.length; i++) {
		const ch = text[i];
		const next = text[i + 1];
		if (inString) {
			out += ch;
			if (ch === "\\") {
				out += next ?? "";
				i++;
			} else if (ch === '"') inString = false;
		} else if (ch === '"') {
			inString = true;
			out += ch;
		} else if (ch === "/" && next === "/") {
			while (i < text.length && text[i] !== "\n") i++;
			out += "\n";
		} else if (ch === "/" && next === "*") {
			i += 2;
			while (i < text.length && !(text[i] === "*" && text[i + 1] === "/")) i++;
			i++;
		} else out += ch;
	}
	return out;
}

export function buildConfig(template, env) {
	const missing = ["KITTING_DOMAIN", "D1_DATABASE_ID", "TEAM_DOMAIN", "ACCESS_AUD", "ADMIN_EMAILS"].filter(
		(k) => !env[k] || !String(env[k]).trim(),
	);
	if (missing.length) throw new Error(`Missing required variables: ${missing.join(", ")}`);
	const domain = env.KITTING_DOMAIN.trim()
		.replace(/^https?:\/\//, "")
		.replace(/\/+$/, "");
	if (domain.includes("workers.dev")) throw new Error("KITTING_DOMAIN must be a custom domain, not *.workers.dev");
	const locale = (env.DEFAULT_LOCALE || "en").trim();
	if (!["en", "fr"].includes(locale)) throw new Error("DEFAULT_LOCALE must be en or fr");

	const config = JSON.parse(stripJsonComments(template));
	config.name = env.WORKER_NAME?.trim() || config.name;
	config.workers_dev = false;
	config.preview_urls = false;
	config.routes = [{ pattern: domain, custom_domain: true }];
	config.d1_databases[0].database_id = env.D1_DATABASE_ID.trim();
	config.d1_databases[0].database_name = env.D1_DATABASE_NAME?.trim() || config.d1_databases[0].database_name;
	config.vars = {
		...config.vars,
		ENVIRONMENT: "production",
		TEAM_DOMAIN: env.TEAM_DOMAIN.trim(),
		ACCESS_AUD: env.ACCESS_AUD.trim(),
		ADMIN_EMAILS: env.ADMIN_EMAILS.trim(),
		DEFAULT_LOCALE: locale,
		CURRENCY: (env.CURRENCY || "EUR").trim().toUpperCase(),
		DEV_AUTH_EMAIL: "",
	};
	return config;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
	try {
		const template = readFileSync(join(root, "wrangler.example.jsonc"), "utf8");
		const config = buildConfig(template, process.env);
		const header = "// Generated by scripts/gen-wrangler-config.mjs. Do not commit.\n";
		writeFileSync(join(root, "wrangler.jsonc"), `${header}${JSON.stringify(config, null, 2)}\n`);
		console.log(`wrangler.jsonc written for ${config.routes[0].pattern} (worker "${config.name}")`);
	} catch (err) {
		console.error(`Cannot generate wrangler.jsonc: ${err.message}`);
		process.exit(1);
	}
}
