// SQL of the history triggers (D107), generated from the Drizzle schema so that no column can be forgotten.
// `npm run -s db:triggers` prints it for a migration (scripts/history-triggers.mjs); test/history.test.ts
// checks that the triggers in the database are exactly these. Only package imports here: the script loads
// this file with Node's type stripping, which cannot resolve extensionless local imports.
import { getTableColumns, getTableName } from "drizzle-orm";
import type { SQLiteTable } from "drizzle-orm/sqlite-core";

/** Who/when columns: shown beside each change, not as changed fields, and never a reason to log or refuse. */
export const AUDIT_COLUMNS: readonly string[] = ["created_at", "updated_at", "created_by", "updated_by"];

export const HISTORY_OPS = ["insert", "update", "delete"] as const;

export function columnNames(table: SQLiteTable): string[] {
	return Object.values(getTableColumns(table)).map((c) => c.name);
}

export const triggerName = (table: string, op: string) => `history_${table}_${op}`;
export const ledgerTriggerName = (table: string) => `history_${table}_ledger`;

const q = (id: string) => `"${id}"`;

/** json_object('col', NEW."col", …) over every column: the full row. */
function rowJson(ref: "NEW" | "OLD", columns: string[]): string {
	return `json_object(${columns.map((c) => `'${c}', ${ref}.${q(c)}`).join(", ")})`;
}

// Triggers do nothing while a restore suppresses them, and abort any write made without an open change set.
const WHEN_NOT_SUPPRESSED = "WHEN NOT EXISTS (SELECT 1 FROM change_context WHERE suppress = 1)";
const abortOutsideChangeSet = (table: string) =>
	`SELECT RAISE(ABORT, 'history: write to ${table} outside a change set') WHERE NOT EXISTS (SELECT 1 FROM change_context WHERE change_set_id IS NOT NULL);`;

/** The CREATE TRIGGER statements of one tracked table (insert, update, delete), as SQLite stores them. */
export function tableTriggers(table: SQLiteTable): { name: string; sql: string }[] {
	const name = getTableName(table);
	const columns = columnNames(table);
	const insertLog = (op: string, rowId: string, oldRow: string, newRow: string, where = "") =>
		`INSERT INTO change_log (change_set_id, table_name, row_id, op, old_row, new_row)
	SELECT change_set_id, '${name}', ${rowId}, '${op}', ${oldRow}, ${newRow} FROM change_context${where};`;
	// An update is logged when a column other than who/when changed (a "touch" only bumps updated_at).
	const changed = columns
		.filter((c) => !AUDIT_COLUMNS.includes(c))
		.map((c) => `OLD.${q(c)} IS NOT NEW.${q(c)}`)
		.join(" OR ");
	const trigger = (op: string, event: string, body: string) => ({
		name: triggerName(name, op),
		sql: `CREATE TRIGGER ${q(triggerName(name, op))} AFTER ${event} ON ${q(name)}
${WHEN_NOT_SUPPRESSED}
BEGIN
	${abortOutsideChangeSet(name)}
	${body}
END`,
	});
	return [
		trigger("insert", "INSERT", insertLog("insert", 'NEW."id"', "NULL", rowJson("NEW", columns))),
		trigger(
			"update",
			"UPDATE",
			insertLog("update", 'NEW."id"', rowJson("OLD", columns), rowJson("NEW", columns), `\n\tWHERE ${changed}`),
		),
		trigger("delete", "DELETE", insertLog("delete", 'OLD."id"', rowJson("OLD", columns), "NULL")),
	];
}

/** The trigger that makes a change set writing to a ledger non-revertible. */
export function ledgerTrigger(table: SQLiteTable): { name: string; sql: string } {
	const name = getTableName(table);
	return {
		name: ledgerTriggerName(name),
		sql: `CREATE TRIGGER ${q(ledgerTriggerName(name))} AFTER INSERT ON ${q(name)}
BEGIN
	UPDATE change_sets SET revertible = 0 WHERE id = (SELECT change_set_id FROM change_context);
END`,
	};
}

/** Every history trigger, dropped first so that a later migration can re-create them after a schema change. */
export function historyTriggersSql(tracked: SQLiteTable[], ledgers: SQLiteTable[]): string {
	const triggers = [...tracked.flatMap(tableTriggers), ...ledgers.map(ledgerTrigger)];
	const lines = [
		"-- History triggers, generated by `npm run -s db:triggers` from src/db/schema.ts (D107). Do not edit by hand.",
		...triggers.flatMap((t) => [
			`DROP TRIGGER IF EXISTS ${q(t.name)};--> statement-breakpoint`,
			`${t.sql};--> statement-breakpoint`,
		]),
	];
	return `${lines.join("\n")}\n`;
}
